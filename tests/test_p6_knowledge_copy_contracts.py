def test_vector_hash_identity_profile_and_f64_label() -> None:
    item = embedding(vector=(0.1, 1.0))
    assert item.evidence_mode == "synthetic_vector"
    # 0.1 differs after float32 rounding. K1 explicitly hashes f64 hex values, not PG bytes.
    import struct

    rounded = struct.unpack("!f", struct.pack("!f", 0.1))[0]
    assert rounded != 0.1
    assert (
        vector_digest(item.profile, item.citation.evidence_id, (rounded, 1.0)) != item.vector_sha256
    )
    for changes in (
        {"vector_sha256": ZERO_HASH},
        {"evidence_mode": "actual_provider"},
        {"profile": profile(profile_version="v2")},
    ):
        with pytest.raises(ValueError):
            Embedding.model_validate(item.model_dump(mode="python") | changes)


