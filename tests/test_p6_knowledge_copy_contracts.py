    assert [h.embedding.citation.chunk.document.document_id for h in a.hits] == [
        "a",
        "b",
        "below",
        "z",
    ]
    assert a.hits[-1].distance == 0.35
    assert Retrieval.model_validate_json(a.model_dump_json()) == a


