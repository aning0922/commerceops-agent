def test_stable_tie_order_reordering_and_threshold_both_sides() -> None:
    # q=(1,0); vector=(13,sqrt(231)) has norm20 and distance1-13/20=0.35.
    edge = (13.0, math.sqrt(231.0))
    items = (
        embedding("z", edge),
        embedding("b"),
        embedding("a"),
        embedding("below", (13.000001, edge[1])),
        embedding("above", (12.999999, edge[1])),
    )
    m = manifest(items)
    a = retrieve(m, query(), items, now=NOW, complete=True)
