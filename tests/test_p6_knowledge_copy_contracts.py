def sha(value: str) -> str:
    return hashlib.sha256(value.encode()).hexdigest()


def seal[T: Contract](model: type[T], field: str, **data: Any) -> T:
    # Fixture construction only. Expected ranking/text below is not generated by production ranking.
    raw = model.model_construct(**data)
    payload = raw.model_dump(mode="json", exclude={field})
    encoded = json.dumps(payload, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
    return model.model_validate(dict(data, **{field: sha(encoded)}))


def changed[T: Contract](value: T, field: str, **changes: Any) -> T:
    data = {name: getattr(value, name) for name in type(value).model_fields if name != field}
    return seal(type(value), field, **(data | changes))


