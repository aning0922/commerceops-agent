def embedding(
    name: str = "doc-a",
    vector: tuple[float, ...] = (1.0, 0.0),
    doc: Document | None = None,
    prof: Profile | None = None,
    chunk_id: str = "chunk-1",
) -> Embedding:
    doc = doc or document(name)
    prof = prof or profile()
    chunk = Chunk(
        document=doc,
        chunk_id=chunk_id,
        chunk_version="v1",
        chunker_version="fixture-v1",
        section="名称核对",
        start=8,
        end=22,
        text=SPAN,
        text_sha256=sha(SPAN),
    )
    citation = seal(SopCitation, "evidence_id", chunk=chunk)
    return Embedding(
        citation=citation,
        profile=prof,
        vector=vector,
        vector_sha256=vector_digest(prof, citation.evidence_id, vector),
    )


def manifest(items: tuple[Embedding, ...], **changes: Any) -> Manifest:
    docs = {e.citation.chunk.document.document_id: e.citation.chunk.document for e in items}
    data: dict[str, Any] = dict(
        scope=SCOPE,
        manifest_version="synthetic-v1",
        profile=profile(),
        documents=tuple(DocumentBinding.of(docs[k]) for k in sorted(docs)),
        evidence_ids=tuple(sorted(e.citation.evidence_id for e in items)),
    )
    return seal(Manifest, "manifest_digest", **(data | changes))


